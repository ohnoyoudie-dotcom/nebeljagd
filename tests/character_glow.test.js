import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createCharacterGlow } from '../src/character-glow.js';
import { createLevelUpEffect } from '../src/level-up-effect.js';

test('a body flash restores each material exactly and preserves texture and concealment', () => {
  const texture = new THREE.Texture();
  const body = new THREE.MeshStandardMaterial({ map: texture, emissive: '#182637', emissiveIntensity: .24, opacity: .35, transparent: true });
  const eyes = new THREE.MeshStandardMaterial({ emissive: '#aabbcc', emissiveIntensity: 1.8 });
  const unlit = new THREE.MeshBasicMaterial({ color: '#112233' });
  const original = [body, eyes].map(material => ({ color: material.emissive.clone(), intensity: material.emissiveIntensity }));
  const glow = createCharacterGlow([body, body, eyes, unlit]);
  glow.set(1);
  assert.equal(glow.inspect().count, 2);
  assert.equal(glow.inspect().restored, false);
  assert.ok(body.emissiveIntensity > original[0].intensity);
  assert.equal(body.map, texture);
  assert.equal(body.opacity, .35);
  assert.equal(body.transparent, true);
  assert.equal(unlit.color.getHexString(), '112233');
  glow.set(.4);
  glow.reset();
  [body, eyes].forEach((material, index) => {
    assert.ok(material.emissive.equals(original[index].color));
    assert.equal(material.emissiveIntensity, original[index].intensity);
  });
  assert.equal(glow.inspect().restored, true);
  glow.set(3);
  assert.equal(glow.strength, 1);
  glow.set(NaN);
  assert.equal(glow.strength, 0);
  assert.equal(glow.inspect().restored, true);
  [body, eyes, unlit, texture].forEach(resource => resource.dispose());
});

test('a real level-up timeline releases its body glow on expiry, restart, reset and disposal', () => {
  const scene = new THREE.Scene();
  const body = new THREE.MeshStandardMaterial({ emissive: '#102030', emissiveIntensity: .4 });
  const glow = createCharacterGlow([body]);
  const effect = createLevelUpEffect(scene, { onGlow: glow.set });
  const position = new THREE.Vector3(4, 0, 8);
  effect.trigger({ position, level: 2 });
  effect.update(.10, position);
  assert.ok(glow.strength > .9);
  assert.equal(glow.inspect().restored, false);
  assert.ok(effect.inspect().particleCount > 0);
  effect.trigger({ position, level: 3 });
  assert.equal(glow.inspect().restored, true);
  effect.update(.10, position);
  effect.reset();
  assert.equal(glow.inspect().restored, true);
  assert.equal(effect.inspect().active, false);
  effect.trigger({ position, level: 2 });
  effect.update(.10, position);
  effect.update(2, position);
  assert.equal(glow.inspect().restored, true);
  assert.equal(effect.inspect().particleCount, 0);
  effect.trigger({ position, level: 2, reducedMotion: true });
  effect.update(.20, position);
  assert.ok(glow.strength > 0 && glow.strength <= .3);
  assert.equal(effect.inspect().particleCount, 0);
  assert.equal(effect.inspect().coreVisible, false);
  effect.dispose();
  assert.equal(glow.inspect().restored, true);
  assert.equal(scene.children.length, 0);
  effect.trigger({ position, level: 3 });
  assert.equal(effect.inspect().active, false);
  body.dispose();
});
